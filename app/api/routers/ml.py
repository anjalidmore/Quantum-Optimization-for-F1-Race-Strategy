router = APIRouter(prefix="/api/ml", tags=["machine-learning"])


def _model_importance(target: str) -> tuple[str, dict[str, float]] | None:
    """(model_name, {feature: importance}) for the target's currently
    selected-best model, or None if that model has no native importance
    (e.g. SVM/SVR) or isn't available."""
    cache = get_model_cache()
    try:
        name, pipeline = cache.get_pipeline(target)
    except ModelUnavailableError:
        return None
    model = pipeline.named_steps["model"]
    names_raw = pipeline.named_steps["preprocess"].get_feature_names_out()
    names = [n.split("__", 1)[-1] for n in names_raw]
    if hasattr(model, "feature_importances_"):
        values = model.feature_importances_.tolist()
    elif hasattr(model, "coef_"):
        values = [abs(c) for c in model.coef_.ravel().tolist()]
    else:
        return name, {}
    return name, dict(zip(names, values))


def _read_json(path):
    if not path.exists():
        raise HTTPException(
            status_code=404,
            detail=f"No trained-model artifact at {path}. Run the training pipeline "
            "(scripts/build_all.py) to generate it.",
        )
    with open(path) as f:
        return json.load(f)


@router.get("/models")
def list_models():
    cache = get_model_cache()
    registry = cache.registry()
    if not registry:
        raise HTTPException(
            status_code=404,
            detail="No model registry found. Run the training pipeline (scripts/build_all.py) first.",
        )
    return registry


